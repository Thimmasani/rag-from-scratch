"""
The generation layer, Part 5 of the RAG-from-scratch series.

Takes retrieved (and reranked) context chunks and actually produces an
answer. Three design decisions in this module exist because the obvious,
naive approach demonstrably failed when tested:

1. ABSTENTION is a separate step, not a single generation instruction.
   Asking the model to "answer, or say you don't know if the context
   doesn't help" in one shot is unreliable -- tested directly, a small
   instruction-tuned model confidently answered "The capital of France is
   Paris" from context about car maintenance and weather, then fabricated
   a tortured justification connecting the two. Splitting this into an
   explicit YES/NO relevance check BEFORE generation, with the abstention
   message hard-coded in Python (not generated) rather than hoped for,
   fixed this reliably across repeated tests.

2. CITATIONS are attributed programmatically, not generated by the model.
   Explicitly instructing the model to "cite sources inline like [1]"
   produced correct, well-grounded answers that simply dropped the
   citation markers entirely, every time, even with the relevance-check
   step in place. Rather than trust the model's instruction-following for
   this, citations are attributed after generation via lexical token
   overlap between each generated sentence and each context chunk --
   reusing Part 1's tokenizer, since this is the same term-overlap idea
   BM25/TF-IDF are built on, just applied to attribution instead of
   ranking.

3. The model: Qwen2.5-0.5B-Instruct (~1GB, ~500M parameters). Small enough
   to run on CPU in a few seconds, which is also exactly why it needs the
   two guardrails above -- a bigger, more expensive model might follow
   single-shot instructions more reliably, but the point of this part is
   that a RAG pipeline's generation layer shouldn't have to assume that.
"""

import re

from transformers import AutoModelForCausalLM, AutoTokenizer

from tfidf import tokenize  # reused for citation attribution, see module docstring

# Citation attribution needs its own stopword filter on top of Part 1's
# tokenize(). tokenize() deliberately keeps every token, including "the",
# "an", "is" -- Part 1's hand-worked IDF table explicitly lists "the" as a
# term, so tokenize() itself must not change. But for citation attribution
# specifically, two sentences sharing only common words like "the" and
# "weekend" can cross a token-overlap threshold without actually being
# about the same thing -- caught directly: a sentence about weekend
# weather was incorrectly attributed to a document about weekend car sales
# because they shared "weekend" and "the" (a stopword), hitting the
# overlap threshold on an accidental word, not real topical overlap.
_STOPWORDS = {
    "a", "an", "and", "are", "as", "at", "be", "by", "for", "from", "has",
    "he", "in", "is", "it", "its", "of", "on", "or", "that", "the", "this",
    "to", "was", "were", "will", "with",
}


def _content_tokens(text: str) -> set[str]:
    return set(tokenize(text)) - _STOPWORDS


class Generator:
    def __init__(self, model_name: str = "Qwen/Qwen2.5-0.5B-Instruct"):
        self.tokenizer = AutoTokenizer.from_pretrained(model_name)
        self.model = AutoModelForCausalLM.from_pretrained(model_name)

    def _generate(self, prompt: str, max_new_tokens: int) -> str:
        messages = [{"role": "user", "content": prompt}]
        text = self.tokenizer.apply_chat_template(messages, tokenize=False, add_generation_prompt=True)
        inputs = self.tokenizer(text, return_tensors="pt")
        outputs = self.model.generate(**inputs, max_new_tokens=max_new_tokens, do_sample=False)
        return self.tokenizer.decode(outputs[0][inputs["input_ids"].shape[1] :], skip_special_tokens=True).strip()

    def _is_relevant(self, query: str, numbered_context: str) -> bool:
        """Step 1: a dedicated relevance check, separate from generation.
        See module docstring -- this is more reliable than a single-shot
        'answer or say you don't know' instruction."""
        prompt = f"""Context:
{numbered_context}

Question: {query}

Does the context above contain information that directly answers the question? Respond with exactly one word: YES or NO."""
        response = self._generate(prompt, max_new_tokens=5)
        return response.upper().startswith("YES")

    def _generate_grounded_answer(self, query: str, numbered_context: str) -> str:
        prompt = f"""Answer the question using ONLY the numbered context below.

Context:
{numbered_context}

Question: {query}

Answer:"""
        return self._generate(prompt, max_new_tokens=120)

    def answer(self, query: str, context_chunks: list[str], min_citation_overlap: int = 2) -> dict:
        """
        Returns a dict with:
          - answer: the final answer text (fixed abstention message, or generated)
          - grounded: bool, whether the relevance check passed
          - citations: list of (sentence, [source_indices]) for each answer sentence
                       (empty if abstained)
        """
        numbered = "\n".join(f"[{i + 1}] {chunk}" for i, chunk in enumerate(context_chunks))

        if not self._is_relevant(query, numbered):
            return {
                "answer": "I don't know based on the given context.",
                "grounded": False,
                "citations": [],
            }

        raw_answer = self._generate_grounded_answer(query, numbered)
        citations = self._attribute_citations(raw_answer, context_chunks, min_citation_overlap)
        return {
            "answer": raw_answer,
            "grounded": True,
            "citations": citations,
        }

    @staticmethod
    def _attribute_citations(
        answer_text: str,
        context_chunks: list[str],
        min_overlap: int,
    ) -> list[tuple[str, list[int]]]:
        """Step 2: programmatic citation attribution (see module docstring).
        For each sentence in the answer, cite every context chunk sharing
        at least `min_overlap` tokens with that sentence."""
        sentences = re.split(r"(?<=[.!?])\s+", answer_text.strip())
        chunk_token_sets = [_content_tokens(chunk) for chunk in context_chunks]

        results = []
        for sentence in sentences:
            if not sentence:
                continue
            sentence_tokens = _content_tokens(sentence)
            cited = [
                i
                for i, chunk_tokens in enumerate(chunk_token_sets)
                if len(sentence_tokens & chunk_tokens) >= min_overlap
            ]
            results.append((sentence, cited))
        return results


def format_with_citations(citations: list[tuple[str, list[int]]]) -> str:
    parts = []
    for sentence, sources in citations:
        tags = "".join(f"[{i + 1}]" for i in sources)
        parts.append(f"{sentence} {tags}".strip())
    return " ".join(parts)


if __name__ == "__main__":
    generator = Generator()

    print("=== Grounded, answerable query ===")
    result = generator.answer(
        "What does the car need?",
        ["the car needs an oil change and new brake pads"],
    )
    print("Grounded:", result["grounded"])
    print("Answer:", format_with_citations(result["citations"]) if result["grounded"] else result["answer"])
    print()

    print("=== Multi-source query, with citations ===")
    result = generator.answer(
        "What car maintenance is needed and is there a SKU on back order?",
        [
            "the car needs an oil change and new brake pads",
            "replacement part SKU-48213-B is on back order until next week",
        ],
    )
    print("Grounded:", result["grounded"])
    print("Answer:", format_with_citations(result["citations"]) if result["grounded"] else result["answer"])
    print()

    print("=== Query with NO relevant context (should abstain) ===")
    result = generator.answer(
        "What is the capital of France?",
        [
            "the car needs an oil change and new brake pads",
            "the weather today is sunny with a light breeze in the afternoon",
        ],
    )
    print("Grounded:", result["grounded"])
    print("Answer:", result["answer"])
